<?php declare( strict_types=1 );

namespace Merkushin\Wpal\Tools\Docs;

use Merkushin\Wpal\Tools\Api\DocBlock;
use Merkushin\Wpal\Tools\Api\Parameter;
use Merkushin\Wpal\Tools\Api\SignatureBuilder;
use Merkushin\Wpal\Tools\Api\Snapshot;
use Merkushin\Wpal\Tools\Coverage\Map;
use PhpParser\Node\Stmt;
use PhpParser\NodeFinder;
use PhpParser\ParserFactory;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;

/**
 * Builds the API reference, the Service index and llms.txt from the code, so they can't drift from it.
 */
final class DocsGenerator {
	private const REPOSITORY = 'https://github.com/merkushin/WPAL/blob/main';

	public function __construct( private string $root, private Map $map, private Snapshot $wordpress ) {
	}

	/**
	 * @return array<string, string> Path relative to the project root => contents.
	 */
	public function generate(): array {
		return [
			'docs/api.md'      => $this->apiReference(),
			'docs/services.md' => $this->serviceIndex(),
			'llms.txt'         => $this->llmsTxt(),
		];
	}

	private function apiReference(): string {
		$sections = [];
		foreach ( $this->apiTypes() as $type ) {
			$sections[] = $this->typeSection( $type['name'], $type['node'] );
		}

		return "<!-- Generated by bin/wpal docs from src/Api. Do not edit. -->\n\n"
			. "# WPAL Api reference\n\n"
			. "The designed API (PHP 8.4+). Start with `new Merkushin\\Wpal\\Wpal()`; see the [README](../README.md) for an overview.\n\n"
			. implode( "\n", $sections );
	}

	/**
	 * Public Api types in reading order: entry point and service interfaces first, then their helpers, then fakes.
	 *
	 * @return list<array{name: string, node: Stmt\ClassLike}>
	 */
	private function apiTypes(): array {
		$parser = ( new ParserFactory() )->createForNewestSupportedVersion();
		$finder = new NodeFinder();
		$types  = [];

		$files = [ $this->root . '/src/Wpal.php' ];
		foreach ( new RecursiveIteratorIterator( new RecursiveDirectoryIterator( $this->root . '/src/Api', RecursiveDirectoryIterator::SKIP_DOTS ) ) as $file ) {
			$files[] = $file->getPathname();
		}

		foreach ( $files as $file ) {
			if ( str_contains( $file, '/Api/WordPress/' ) || substr( $file, -4 ) !== '.php' ) {
				continue;
			}
			$ast       = $parser->parse( (string) file_get_contents( $file ) ) ?? [];
			$namespace = $finder->findFirstInstanceOf( $ast, Stmt\Namespace_::class );
			foreach ( $finder->findInstanceOf( $ast, Stmt\ClassLike::class ) as $node ) {
				/** @var Stmt\ClassLike $node */
				$doc = new DocBlock( $node->getDocComment()?->getText() );
				if ( $node->name === null || $node instanceof Stmt\Trait_ || $doc->has( 'internal' ) ) {
					continue;
				}
				$name    = ( $namespace instanceof Stmt\Namespace_ && $namespace->name !== null ? $namespace->name->toString() . '\\' : '' ) . $node->name->toString();
				$types[] = [ 'name' => $name, 'node' => $node ];
			}
		}

		usort( $types, fn ( array $a, array $b ): int => [ $this->rank( $a['name'] ), $a['name'] ] <=> [ $this->rank( $b['name'] ), $b['name'] ] );

		return $types;
	}

	private function rank( string $name ): int {
		return match ( true ) {
			$name === 'Merkushin\\Wpal\\Wpal'                            => 0,
			substr_count( $name, '\\' ) === 3                             => 1,
			str_contains( $name, '\\Testing\\' )                         => 4,
			str_contains( $name, '\\Exception\\' )                       => 3,
			default                                                      => 2,
		};
	}

	private function typeSection( string $name, Stmt\ClassLike $node ): string {
		$short = str_replace( 'Merkushin\\Wpal\\', '', $name );
		$kind  = match ( true ) {
			$node instanceof Stmt\Interface_ => 'interface',
			$node instanceof Stmt\Enum_      => 'enum',
			default                          => ( $node instanceof Stmt\Class_ && $node->isFinal() ? 'final ' : '' ) . ( $node instanceof Stmt\Class_ && $node->isReadonly() ? 'readonly ' : '' ) . 'class',
		};

		$out = "## {$short}\n\n`{$kind} {$name}`\n\n" . $this->description( $node->getDocComment()?->getText() );

		if ( $node instanceof Stmt\Enum_ ) {
			$cases = array_map( static fn ( Stmt\EnumCase $case ): string => '`' . $case->name->toString() . '`', array_values( array_filter( $node->stmts, static fn ( $s ): bool => $s instanceof Stmt\EnumCase ) ) );

			return $out . 'Cases: ' . implode( ', ', $cases ) . "\n";
		}

		$properties = $this->properties( $node );
		if ( $properties !== [] ) {
			$out .= "| Property | Type | |\n| --- | --- | --- |\n" . implode( "\n", $properties ) . "\n\n";
		}

		$methods = $this->methods( $node );
		if ( $methods !== [] ) {
			$out .= implode( "\n", $methods ) . "\n";
		}

		return $out;
	}

	/**
	 * Public properties, including promoted ones and `public private(set)` state.
	 *
	 * @return list<string>
	 */
	private function properties( Stmt\ClassLike $node ): array {
		$builder = new SignatureBuilder();
		$rows    = [];
		foreach ( $node->getProperties() as $property ) {
			if ( ! $property->isPublic() ) {
				continue;
			}
			$doc     = $property->getDocComment()?->getText();
			$type    = (string) $builder->type( $property->type );
			$summary = $this->summary( $doc );
			// `@var list<string> Description` says more than `array` and an empty summary.
			if ( $doc !== null && preg_match( '#@var[ \t]+([^\n]+)#', $doc, $var ) === 1 ) {
				[ $type, $description ] = $this->splitType( rtrim( $var[1], " \t*/" ) );
				$summary                = $summary !== '' ? $summary : $description;
			}
			foreach ( $property->props as $prop ) {
				$rows[] = sprintf( '| `$%s` | `%s` | %s |', $prop->name->toString(), str_replace( '|', '\\|', $type ), $summary );
			}
		}
		$constructor = $node->getMethod( '__construct' );
		foreach ( $constructor->params ?? [] as $param ) {
			if ( ( $param->flags & Stmt\Class_::MODIFIER_PUBLIC ) === 0 ) {
				continue;
			}
			$parameter = $builder->parameter( $param );
			$rows[]    = sprintf( '| `$%s` | `%s` | |', $parameter->name, (string) $parameter->type );
		}

		return $rows;
	}

	/**
	 * @return list<string>
	 */
	private function methods( Stmt\ClassLike $node ): array {
		$builder = new SignatureBuilder();
		$items   = [];
		foreach ( $node->getMethods() as $method ) {
			if ( ! $method->isPublic() || str_starts_with( $method->name->toString(), '__' ) ) {
				continue;
			}
			$params    = implode( ', ', array_map( static fn ( Parameter $p ): string => $p->describe(), $builder->parameters( $method->params ) ) );
			$doc       = $method->getDocComment()?->getText();
			// A documented return type (list<Post>) says more than the native one (array).
			$return = $builder->type( $method->returnType );
			if ( $doc !== null && preg_match( '/@return[ \t]+(\S+)/', $doc, $documented ) === 1 && in_array( $return, [ 'array', '?array', 'mixed' ], true ) ) {
				$return = $documented[1];
			}
			$signature = ( $method->isStatic() ? 'static ' : '' ) . $method->name->toString() . "( {$params} )" . ( $return !== null ? ": {$return}" : '' );
			$signature = str_replace( '(  )', '()', $signature );
			$summary   = $this->summary( $doc );
			$throws    = $this->throws( $doc );

			$items[] = "- `{$signature}`" . ( $summary !== '' ? "  \n  {$summary}" : '' ) . ( $throws !== '' ? "  \n  Throws {$throws}." : '' );
		}

		return $items;
	}

	/**
	 * The docblock's text before its tags, with indented examples as PHP code blocks.
	 */
	private function description( ?string $doc ): string {
		$lines = $this->prose( $doc );
		if ( $lines === [] ) {
			return '';
		}

		$out     = '';
		$inCode  = false;
		$pending = 0;
		foreach ( $lines as $line ) {
			if ( trim( $line ) === '' ) {
				// Held back so a code block closes right after its last line.
				++$pending;
				continue;
			}
			$isCode = str_starts_with( $line, '    ' );
			if ( $isCode && ! $inCode ) {
				$out   .= str_repeat( "\n", $pending ) . "```php\n";
				$inCode = true;
			} elseif ( ! $isCode && $inCode ) {
				$out   .= "```\n" . str_repeat( "\n", $pending );
				$inCode = false;
			} else {
				$out .= str_repeat( "\n", $pending );
			}
			$pending = 0;
			$out    .= ( $isCode ? substr( $line, 4 ) : $line ) . "\n";
		}
		if ( $inCode ) {
			$out .= "```\n";
		}

		return trim( $out ) . "\n\n";
	}

	private function summary( ?string $doc ): string {
		$lines     = $this->prose( $doc );
		$paragraph = [];
		foreach ( $lines as $line ) {
			if ( trim( $line ) === '' || str_starts_with( $line, '    ' ) ) {
				break;
			}
			$paragraph[] = trim( $line );
		}

		return implode( ' ', $paragraph );
	}

	/**
	 * Splits `array<string, mixed> Some text` into the type and the text, respecting brackets in the type.
	 *
	 * @return array{0: string, 1: string}
	 */
	private function splitType( string $text ): array {
		$depth = 0;
		$len   = strlen( $text );
		for ( $i = 0; $i < $len; $i++ ) {
			$char = $text[ $i ];
			if ( $char === '<' || $char === '(' || $char === '{' || $char === '[' ) {
				++$depth;
			} elseif ( $char === '>' || $char === ')' || $char === '}' || $char === ']' ) {
				--$depth;
			} elseif ( $depth === 0 && ( $char === ' ' || $char === "\t" ) && ! in_array( $text[ $i - 1 ] ?? '', [ ',', ':', '|' ], true ) && ! in_array( $text[ $i + 1 ] ?? '', [ '|' ], true ) ) {
				return [ substr( $text, 0, $i ), trim( substr( $text, $i ) ) ];
			}
		}

		return [ $text, '' ];
	}

	private function throws( ?string $doc ): string {
		if ( $doc === null || ! preg_match_all( '/@throws[ \t]+(\S+)(?:[ \t]+([^\n]*))?/', $doc, $m, PREG_SET_ORDER ) ) {
			return '';
		}

		return implode( '; ', array_map( static fn ( array $t ): string => '`' . ltrim( $t[1], '\\' ) . '`' . ( isset( $t[2] ) && trim( $t[2] ) !== '' ? ' ' . lcfirst( rtrim( trim( $t[2] ), '.' ) ) : '' ), $m ) );
	}

	/**
	 * @return list<string> Docblock lines before the first tag, without the comment markers.
	 */
	private function prose( ?string $doc ): array {
		if ( $doc === null ) {
			return [];
		}
		$lines = [];
		foreach ( explode( "\n", $doc ) as $line ) {
			$line = preg_replace( '#^\s*/\*\*\s?|\s*\*/\s*$|^\s*\*\s?#', '', $line ) ?? '';
			if ( str_starts_with( ltrim( $line ), '@' ) ) {
				break;
			}
			$lines[] = rtrim( $line );
		}
		while ( $lines !== [] && trim( $lines[0] ) === '' ) {
			array_shift( $lines );
		}
		while ( $lines !== [] && trim( (string) end( $lines ) ) === '' ) {
			array_pop( $lines );
		}

		return $lines;
	}

	private function serviceIndex(): string {
		$services = $this->map->services();
		ksort( $services, SORT_STRING );
		$count = array_sum( array_map( 'count', $services ) );

		$out = "<!-- Generated by bin/wpal docs from wpal.map.php. Do not edit. -->\n\n"
			. "# WPAL Service index\n\n"
			. sprintf( "%d methods in %d services, one per WordPress %s function, with WordPress's own signature and docblock. ", $count, count( $services ), $this->wordpress->version )
			. "Get a service with `ServiceFactory::create_<snake_case_name>()`, e.g. `ServiceFactory::create_rest_api()`.\n\n";

		foreach ( $services as $service => $functions ) {
			$names = array_map( fn ( string $f ): string => $this->wordpress->get( $f )->name ?? $f, $functions );
			$out  .= "## {$service}\n\n" . implode( ', ', array_map( static fn ( string $n ): string => "`{$n}`", $names ) ) . "\n\n";
		}

		return rtrim( $out ) . "\n";
	}

	private function llmsTxt(): string {
		$services = $this->map->services();
		$methods  = array_sum( array_map( 'count', $services ) );
		$repo     = self::REPOSITORY;

		return <<<TXT
# WPAL

> WPAL is a PHP library for writing WordPress plugins with a typed, testable API instead of calling WordPress functions directly. The Api layer (PHP 8.4+, entry point `new Merkushin\\Wpal\\Wpal()`) is a designed API with value objects, exceptions instead of WP_Error, and in-memory fakes for tests. The Service layer (PHP 7.4+) wraps all {$methods} public WordPress {$this->wordpress->version} functions in {$this->count( $services )} services with WordPress's own signatures.

When writing plugin code with WPAL:

- Prefer the Api layer: `\$wp = new Wpal(); \$wp->hooks()`, `->options()`, `->assets()`, `->posts()`, `->abilities()`, `->ai()`.
- For anything the Api doesn't cover, use the Service layer: `ServiceFactory::create_<service>()->wordpress_function_name( ... )` with WordPress's own arguments. Find the service in the Service index.
- Don't call WordPress functions directly in code you want to unit-test; go through WPAL so tests can swap in fakes.
- In tests, pass fakes: `new Wpal( hooks: new FakeHooks(), options: new FakeOptions( [ ... ] ), ai: new FakeAi( [ 'response' ] ) )`. Use `ServiceFactory::set_custom_<service>( \$mock )` for Service-layer doubles.
- Api methods throw `WordPressError` (with `errorCode`) instead of returning `WP_Error`; `find()` returns null, `get()` throws.
- Register abilities with `\$wp->abilities()->define( 'my-plugin/name' )->...->register()` at any time; WPAL registers them on the right hook.
- In the plugin's release build, run `vendor/bin/wpal-prune --scan=src` after `composer install --no-dev` so the plugin ships only the WPAL services it uses.

## Docs

- [Api reference]({$repo}/docs/api.md): every Api interface, builder, value object and fake, with signatures.
- [Service index]({$repo}/docs/services.md): which service wraps which WordPress function.
- [README]({$repo}/README.md): overview, examples, compatibility promise.

## Contributing

- [AGENTS.md]({$repo}/AGENTS.md): layout, generated code, Api design rules, bin/wpal.
- [Triage skill]({$repo}/.claude/skills/triage-wordpress-functions/SKILL.md): how WordPress functions are assigned to services.

TXT;
	}

	/**
	 * @param array<string, string[]> $services
	 */
	private function count( array $services ): int {
		return count( $services );
	}
}
