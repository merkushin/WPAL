<?php declare( strict_types=1 );

namespace Merkushin\Wpal\Tools\Generate;

use Merkushin\Wpal\Tools\Api\FunctionSignature;
use Merkushin\Wpal\Tools\Api\Parameter;
use Merkushin\Wpal\Tools\Api\Snapshot;
use Merkushin\Wpal\Tools\Coverage\Map;
use RuntimeException;

/**
 * Builds `src/Service`, `ServiceFactory` and its test from `wpal.map.php` and a WordPress snapshot.
 */
final class ServiceGenerator {
	public const MARKER = '// Generated by bin/wpal fix from wpal.map.php and api/wordpress.json. Do not edit.';

	/** Docblock types that are not classes. */
	private const PSEUDO_TYPES = [
		'array', 'array-key', 'bool', 'boolean', 'callable', 'callable-string', 'class-string', 'double', 'false',
		'float', 'int', 'integer', 'iterable', 'list', 'mixed', 'never', 'non-empty-array', 'non-empty-string',
		'null', 'numeric', 'numeric-string', 'object', 'positive-int', 'resource', 'scalar', 'self', 'static',
		'string', 'true', 'void',
	];

	/** Setter parameter names that predate the generator; renaming them would break named arguments. */
	private const FACTORY_PARAMETERS = [ 'Hooks' => 'hooks' ];

	public function __construct( private Snapshot $wordpress, private Map $map ) {
	}

	/**
	 * @return array<string, string> Path relative to the project root => file contents.
	 */
	public function generate(): array {
		$services = $this->map->services();
		ksort( $services, SORT_STRING );

		$files = [];
		foreach ( $services as $service => $functions ) {
			$signatures = array_map( fn ( string $name ): FunctionSignature => $this->function( $service, $name ), $functions );

			$files[ "src/Service/{$service}.php" ]   = $this->interface( $service, $signatures, array_keys( $services ) );
			$files[ "src/Service/Wp{$service}.php" ] = $this->implementation( $service, $signatures );
		}
		$files['src/ServiceFactory.php']        = $this->factory( array_keys( $services ) );
		$files['tests/ServiceFactoryTest.php'] = $this->factoryTest( array_keys( $services ) );

		return $files;
	}

	private function function( string $service, string $name ): FunctionSignature {
		$function = $this->wordpress->get( $name );
		if ( $function === null ) {
			throw new RuntimeException( "wpal.map.php lists {$name}() under {$service}, but WordPress {$this->wordpress->version} has no such function." );
		}

		return $function;
	}

	/**
	 * @param FunctionSignature[] $functions
	 * @param string[]            $services  All generated services, so imports never shadow one.
	 */
	private function interface( string $service, array $functions, array $services ): string {
		$methods = [];
		$imports = [];
		foreach ( $functions as $function ) {
			$doc       = $this->docblock( $function->doc );
			$imports   = array_merge( $imports, $this->classesIn( $doc ) );
			$methods[] = ( $doc !== '' ? $doc . "\n" : '' ) . "\tpublic function " . $this->signature( $function ) . ';';
		}

		$reserved = array_merge( $services, array_map( static fn ( string $s ): string => 'Wp' . $s, $services ) );
		$imports  = array_diff( array_unique( $imports ), $reserved );
		sort( $imports, SORT_STRING | SORT_FLAG_CASE );
		$uses = implode( '', array_map( static fn ( string $class ): string => "use {$class};\n", $imports ) );

		return $this->file( ( $uses !== '' ? $uses . "\n" : '' ) . "interface {$service} {\n" . implode( "\n\n", $methods ) . "\n}\n" );
	}

	/**
	 * @param FunctionSignature[] $functions
	 */
	private function implementation( string $service, array $functions ): string {
		$methods = [];
		foreach ( $functions as $function ) {
			$call      = $function->name . $this->arguments( $function ) . ';';
			$body      = $this->returnsValue( $function ) ? 'return ' . $call : $call;
			$methods[] = "\t/**\n\t * @inheritDoc\n\t */\n\tpublic function " . $this->signature( $function ) . " {\n\t\t{$body}\n\t}";
		}

		$final = $this->map->isExtendable( $service ) ? '' : 'final ';

		return $this->file( "{$final}class Wp{$service} implements {$service} {\n" . implode( "\n\n", $methods ) . "\n}\n" );
	}

	private function file( string $body, string $namespace = 'Merkushin\\Wpal\\Service' ): string {
		return "<?php declare( strict_types=1 );\n\n" . self::MARKER . "\n\nnamespace {$namespace};\n\n" . $body;
	}

	/**
	 * `get_post( $post = null, $output = 'OBJECT', $filter = 'raw' )`. Types are WordPress's own, or pinned in the map.
	 */
	private function signature( FunctionSignature $function ): string {
		$types  = $this->map->types( $function->name );
		$params = [];
		foreach ( $function->parameters as $parameter ) {
			$type     = $types[ $parameter->name ] ?? $parameter->type;
			$params[] = ( $type !== null ? $type . ' ' : '' )
				. ( $parameter->byRef ? '&' : '' )
				. ( $parameter->variadic ? '...' : '' )
				. '$' . $parameter->name
				. ( $parameter->hasDefault() ? ' = ' . $this->defaultValue( $parameter ) : '' );
		}

		$returnType = $this->returnType( $function );
		$return     = $returnType !== null ? ': ' . $returnType : '';

		return $function->name . $this->parenthesize( $params ) . $return;
	}

	private function arguments( FunctionSignature $function ): string {
		return $this->parenthesize(
			array_map( static fn ( Parameter $p ): string => ( $p->variadic ? '...' : '' ) . '$' . $p->name, $function->parameters )
		);
	}

	/**
	 * @param string[] $items
	 */
	private function parenthesize( array $items ): string {
		return $items === [] ? '()' : '( ' . implode( ', ', $items ) . ' )';
	}

	/**
	 * WordPress's default as written, except that constants are replaced by their values: interfaces must load
	 * (and be mocked) without WordPress, where constants such as OBJECT don't exist.
	 */
	private function defaultValue( Parameter $parameter ): string {
		$source = (string) $parameter->default;
		if ( ! $parameter->defaultResolved || ! $this->mentionsConstant( $source ) ) {
			return $source;
		}

		return $this->export( $parameter->defaultValue );
	}

	private function mentionsConstant( string $code ): bool {
		$withoutStrings = preg_replace( '/\'(?:[^\'\\\\]|\\\\.)*\'|"(?:[^"\\\\]|\\\\.)*"/', '', $code ) ?? $code;

		return preg_match( '/\b(?!(?:true|false|null|array)\b)[A-Za-z_]\w*/i', $withoutStrings ) === 1;
	}

	private function export( mixed $value ): string {
		if ( is_array( $value ) ) {
			$items = [];
			foreach ( $value as $key => $item ) {
				$items[] = ( array_is_list( $value ) ? '' : $this->export( $key ) . ' => ' ) . $this->export( $item );
			}

			return $items === [] ? 'array()' : 'array( ' . implode( ', ', $items ) . ' )';
		}
		if ( $value === null ) {
			return 'null';
		}

		return var_export( $value, true );
	}

	private function returnType( FunctionSignature $function ): ?string {
		return $this->map->types( $function->name )['return'] ?? $function->returnType;
	}

	private function returnsValue( FunctionSignature $function ): bool {
		$returnType = $this->returnType( $function );
		if ( $returnType !== null ) {
			return $returnType !== 'void' && $returnType !== 'never';
		}
		if ( $function->doc === null || ! preg_match( '/@return\s+(\S+)/', $function->doc, $m ) ) {
			return false;
		}

		return ! in_array( strtolower( $m[1] ), [ 'void', 'never' ], true );
	}

	/**
	 * WordPress's docblock, re-indented for a method. Empty when WordPress has none.
	 */
	private function docblock( ?string $doc ): string {
		if ( $doc === null || trim( $doc ) === '' ) {
			return '';
		}

		$lines = [];
		foreach ( explode( "\n", trim( $doc ) ) as $line ) {
			$line = $this->qualifyNamespacedTypes( rtrim( ltrim( $line ) ) );
			if ( str_starts_with( $line, '/**' ) ) {
				$lines[] = "\t" . $line;
			} elseif ( str_starts_with( $line, '*' ) ) {
				$lines[] = "\t " . $line;
			} else {
				$lines[] = "\t * " . $line;
			}
		}

		return implode( "\n", $lines );
	}

	/**
	 * `@return SimplePie\SimplePie` would resolve inside our namespace; make such types fully qualified.
	 */
	private function qualifyNamespacedTypes( string $line ): string {
		return (string) preg_replace_callback(
			'/(@(?:param|return|var|type|global|throws)\s+)([^\s$]+)/',
			static fn ( array $m ): string => $m[1] . preg_replace( '/(?<![\\\\\w])([A-Za-z_]\w*(?:\\\\\w+)+)/', '\\\\$1', $m[2] ),
			$line
		);
	}

	/**
	 * Global classes named in docblock types, which need a `use` inside the namespace.
	 *
	 * @return string[]
	 */
	private function classesIn( string $doc ): array {
		if ( ! preg_match_all( '/@(?:param|return|var|type|global|throws)\s+([^\s$]+)/', $doc, $m ) ) {
			return [];
		}

		$classes = [];
		foreach ( $m[1] as $type ) {
			foreach ( preg_split( '/[|&<>,()\[\]{}?:\s]+/', $type ) ?: [] as $token ) {
				if ( preg_match( '/^[A-Za-z_][A-Za-z0-9_]*$/', $token ) !== 1 || in_array( strtolower( $token ), self::PSEUDO_TYPES, true ) ) {
					continue;
				}
				if ( ctype_upper( $token[0] ) || in_array( $token, [ 'wpdb', 'stdClass' ], true ) ) {
					$classes[] = $token;
				}
			}
		}

		return $classes;
	}

	/**
	 * @param string[] $services
	 */
	private function factory( array $services ): string {
		$uses       = [];
		$properties = [];
		$methods    = [];
		foreach ( $services as $service ) {
			$snake        = $this->snake( $service );
			$parameter    = self::FACTORY_PARAMETERS[ $service ] ?? "custom_{$snake}";
			$uses[]       = "use Merkushin\\Wpal\\Service\\{$service};";
			$uses[]       = "use Merkushin\\Wpal\\Service\\Wp{$service};";
			$properties[] = "\t/**\n\t * @var {$service}|null\n\t */\n\tprivate static \$custom_{$snake};";
			$methods[]    = <<<PHP
	public static function set_custom_{$snake}( ?{$service} \${$parameter} ): void {
		self::\$custom_{$snake} = \${$parameter};
	}

	public static function create_{$snake}(): {$service} {
		if ( self::\$custom_{$snake} ) {
			return self::\$custom_{$snake};
		}

		return new Wp{$service}();
	}
PHP;
		}
		sort( $uses, SORT_STRING );

		return $this->file(
			implode( "\n", $uses ) . "\n\nclass ServiceFactory {\n" . implode( "\n\n", $properties ) . "\n\n" . implode( "\n\n", $methods ) . "\n}\n",
			'Merkushin\\Wpal'
		);
	}

	/**
	 * @param string[] $services
	 */
	private function factoryTest( array $services ): string {
		$uses   = [ 'use Merkushin\\Wpal\\ServiceFactory;', 'use PHPUnit\\Framework\\TestCase;' ];
		$resets = [];
		$tests  = [];
		foreach ( $services as $service ) {
			$snake    = $this->snake( $service );
			$uses[]   = "use Merkushin\\Wpal\\Service\\{$service};";
			$uses[]   = "use Merkushin\\Wpal\\Service\\Wp{$service};";
			$resets[] = "\t\tServiceFactory::set_custom_{$snake}( null );";
			$tests[]  = <<<PHP
	public function testCreate{$service}_WhenCalled_ReturnsWp{$service}(): void
	{
		\$actual = ServiceFactory::create_{$snake}();

		self::assertInstanceOf( Wp{$service}::class, \$actual );
	}

	public function testCreate{$service}_WhenCustom{$service}Set_ReturnsCustom{$service}(): void
	{
		\$custom = \$this->createMock( {$service}::class );
		ServiceFactory::set_custom_{$snake}( \$custom );

		\$actual = ServiceFactory::create_{$snake}();

		self::assertSame( \$custom, \$actual );
	}
PHP;
		}
		sort( $uses, SORT_STRING );

		return "<?php declare( strict_types=1 );\n\n" . self::MARKER . "\n\n" . implode( "\n", $uses ) . "\n\n"
			. "/**\n * @covers \\Merkushin\\Wpal\\ServiceFactory\n */\nclass ServiceFactoryTest extends TestCase\n{\n"
			. "\tprotected function tearDown(): void\n\t{\n" . implode( "\n", $resets ) . "\n\t}\n\n"
			. implode( "\n\n", $tests ) . "\n}\n";
	}

	private function snake( string $service ): string {
		return strtolower( (string) preg_replace( '/(?<!^)[A-Z]/', '_$0', $service ) );
	}
}
